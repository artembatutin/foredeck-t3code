describe("pullRequestTextProblems", () => {
  const neutral = {
    title: "feat: fd-aaaaaa Add the export button",
    body: "Work item fd-aaaaaa: Add the export button\n\nAccepted tasks:\n\n1. Add the export button",
    key: "fd-aaaaaa",
  };

  it("passes neutral text, and names only as whole words", () => {
    expect(pullRequestTextProblems(neutral)).toEqual([]);
    expect(
      pullRequestTextProblems({ ...neutral, body: `${neutral.body}\n- gptq quantizes weights` }),
    ).toEqual([]);
  });

  it.each([
    ["a name in the title", { ...neutral, title: "feat: fd-aaaaaa Port Codex" }, "title"],
    ["a name in a command path", { ...neutral, body: "`node tests/codex/verify.mjs`" }, "body"],
    ["a name in a link", { ...neutral, body: "Link: https://github.com/openai/alpha" }, "body"],
  ] as const)("finds %s", (_, text, field) => {
    expect(pullRequestTextProblems(text)).toEqual([{ field, rule: "ai_name" }]);
  });

  it("finds attribution anywhere, with every problem in field order", () => {
    expect(
      pullRequestTextProblems({
        title: "feat: fd-aaaaaa Export, generated with a tool",
        body: `${neutral.body}\n  Assisted-by: Claude`,
        key: "fd-aaaaaa",
      }),
    ).toEqual([
      { field: "title", rule: "ai_attribution" },
      { field: "body", rule: "ai_name" },
      { field: "body", rule: "ai_attribution" },
    ]);
  });

  it.each([
    ["the raw key form", "fd-aaaaaa: Add the export button"],
    ["no type", "Add the export button (fd-aaaaaa)"],
    ["several lines", "feat: fd-aaaaaa Add\nthe button"],
    ["a carriage return", "feat: fd-aaaaaa Add\rthe button"],
    ["no key", "feat: Add the export button"],
    ["only a longer key", "feat: fd-aaaaaa-2 Add the export button"],
    ["only part of a key", "feat: xfd-aaaaaa Add the export button"],
    ["too many characters", `feat: fd-aaaaaa ${"x".repeat(57)}`],
  ])("refuses a title with %s", (_, title) => {
    expect(pullRequestTextProblems({ ...neutral, title })).toEqual([
      { field: "title", rule: "malformed_title" },
    ]);
  });

  it("takes a key anywhere as a whole word", () => {
    expect(pullRequestTextProblems({ ...neutral, title: "feat(web): add it (fd-aaaaaa)" })).toEqual(
      [],
    );
    expect(pullRequestTextProblems({ ...neutral, title: "feat: #12 add it", key: "#12" })).toEqual(
      [],
    );
  });
});

describe("the settle check reads the same rules", () => {
  const settled = (body: string) => {
    const commit: FactoryBranchCommit = {
      sha: "a".repeat(40),
      subject: "feat(server): add the export",
      body,
      authorName: "Ada Lovelace",
      authorEmail: "ada@example.com",
      committerName: "Ada Lovelace",
      committerEmail: "ada@example.com",
    };
    const result = evaluateSettle(
      { branch: "feature/item-7", clean: true, baselineIsAncestor: true, commits: [commit] },
      "feature/item-7",
    );
    return result.status === "settled" ? [] : result.problems.map(({ rule }) => rule);
  };

  it("refuses a commit crediting an assistant, and keeps a human co-author", () => {
    expect(settled("Co-authored-by: GitHub Copilot <copilot@example.com>")).toEqual([
      "ai_name_in_body",
    ]);
    expect(settled("Co-authored-by: AI Assistant <assistant@example.com>")).toEqual([
      "ai_attribution",
    ]);
    expect(settled("Co-authored-by: Ada Lovelace <ada@example.com>")).toEqual([]);
    expect(settled("Co-authored-by: Ai Nguyen <ai.nguyen@example.com>")).toEqual([]);
    expect(settled("Co-authored-by: Ada Cursor <ada@example.com>")).toEqual([]);
    expect(settled("Signed-off-by: Ada Cursor <ada@example.com>")).toEqual([]);
    expect(settled("Co-authored-by: Cursor <cursoragent@cursor.com>")).toEqual(["ai_name_in_body"]);
    expect(settled("Moves the cursor to the end of the line.")).toEqual([]);
  });
});
